"""findhome — the CLI agents, VS Code tasks and you use to drive the app.

Token rules: short ids (L-XXXX), compact fixed-format output, --json for scripts, raw pages
never printed. Everything except `db`, `config validate|show|hash|schema`, `run new` and
`serve` talks to the local API (FINDHOME_API, default http://127.0.0.1:8200).
"""
from __future__ import annotations

import asyncio
import json
import os
import sys
from pathlib import Path
from typing import Optional

import typer

from findhome.cli.client import Api

app = typer.Typer(help=__doc__, no_args_is_help=True, add_completion=False, pretty_exceptions_enable=False)
db_app = typer.Typer(help="Database migrations.", no_args_is_help=True)
config_app = typer.Typer(help="Validate and inspect the YAML configs.", no_args_is_help=True)
listings_app = typer.Typer(help="List, show, change status, give feedback.", no_args_is_help=True)
digest_app = typer.Typer(help="Token-lean digests for agents.", no_args_is_help=True)
ingest_app = typer.Typer(help="Write listings/evaluations from JSON files (agent write path).", no_args_is_help=True)
site_app = typer.Typer(help="Site registry tools.", no_args_is_help=True)
run_app = typer.Typer(help="Agent run folders (scratchpads).", no_args_is_help=True)
scores_app = typer.Typer(help="Scores.", no_args_is_help=True)
for name, sub in (("db", db_app), ("config", config_app), ("listings", listings_app), ("digest", digest_app),
                  ("ingest", ingest_app), ("site", site_app), ("run", run_app), ("scores", scores_app)):
    app.add_typer(sub, name=name)

STATE = {"json": False, "api": None}


@app.callback()
def main(json_out: bool = typer.Option(False, "--json", help="Machine-readable output."),
         api: Optional[str] = typer.Option(None, "--api", envvar="FINDHOME_API", help="API base URL.")):
    STATE["json"], STATE["api"] = json_out, api


def _api() -> Api:
    return Api(STATE["api"])


def _out(data, text: str | None = None) -> None:
    if STATE["json"] or text is None:
        typer.echo(json.dumps(data, indent=2, ensure_ascii=False, default=str))
    else:
        typer.echo(text)


# ── db ──────────────────────────────────────────────────────
@db_app.command("migrate")
def db_migrate(check: bool = typer.Option(False, "--check", help="Exit 1 if migrations are pending.")):
    """Apply pending SQL migrations (backend/migrations)."""
    from findhome.core.settings import get_settings
    from findhome.db.migrate import migrate, status

    url = get_settings().database_url
    if check:
        st = status(url)
        if st.pending or st.changed:
            typer.echo(f"pending: {st.pending or '-'} changed: {st.changed or '-'}")
            raise typer.Exit(1)
        typer.echo(f"up to date ({len(st.applied)} applied)")
        return
    done = migrate(url)
    typer.echo(f"applied: {', '.join(done)}" if done else "nothing to apply")


