@app.command()
def commute(short_ids: list[str], provider: Optional[str] = None, budget: Optional[int] = None,
            dry_run: bool = typer.Option(False, "--dry-run", help="Count provider calls and cost, call nothing.")):
    """Commute matrix: listing ↔ every point/trip/window/mode, cached, within the call budget."""
    api = _api()
    res = api.post("/api/commute/compute", {"short_ids": short_ids, "budget": budget, "dry_run": dry_run,
                                            "provider": provider})
    lines = [f"budget {res['budget_used']}/{res['budget_max']} · providers: "
             + ", ".join(f"{k}={v}" for k, v in res["providers"].items())]
    for sid, r in res["results"].items():
        if "error" in r:
            lines.append(f"{sid}: {r['error']}")
            continue
        by = ", ".join(f"{k} {v}" for k, v in r["by_provider"].items())
        head = (f"{sid}: {r['requests']} requests, {r['cached']} cached, {r['calls']} "
                f"{'would call' if dry_run else 'calls'}{f' ({by})' if by else ''}, {r['estimated']} estimated (haversine)")
        if dry_run and r.get("estimated_cost_usd"):
            head += f", est. cost ${r['estimated_cost_usd']}"
        if r.get("skipped_budget"):
            head += f", {r['skipped_budget']} skipped (budget)"
        if r.get("prefiltered"):
            head += f", prefiltered: {', '.join(r['prefiltered'])}"
        if r.get("missing_coords"):
            head += f", no coords: {', '.join(r['missing_coords'])}"
        if r.get("last_error"):
            head += f"\n  last error: {r['last_error']}"
        lines.append(head)
        if not dry_run:
            for c in api.get(f"/api/commute/{sid}")["items"]:
                lines.append(f"  {c['point_id']} {'→' if c['direction'] == 'to_point' else '←'} {c['window_label']} "
                             f"({c['day_type']}, {c['mode']}): median {c['median_min']}′ p90 {c['p90_min']}′ "
                             f"worst {c['worst_min']}′ [{c['provider']}, {len(c['samples'])} slots]")
    _out(res, "\n".join(lines))


