@site_app.command("probe")
def site_probe(url: str, slug: str = typer.Option(..., "--slug"), name: Optional[str] = None,
               browser: bool = typer.Option(False, "--browser", help="Also load with headless Playwright and record JSON XHR calls")):
    """Inspect a site page (no LLM): data signals, embedded JSON, API calls, robots → recommended fetch method."""
    from findhome.scanning.probe import probe, write_outputs

