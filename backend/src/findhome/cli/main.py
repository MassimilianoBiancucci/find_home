@zone_app.command("heatmap")
def zone_heatmap(zone_id: str, sets: str = typer.Option("rail,bus", "--sets", help="zone.yaml target sets, comma list"),
                 mode: str = typer.Option("walk", "--mode", help="walk | bike"),
                 neighbours: bool = typer.Option(False, "--neighbours", help="include the touching zones")):
    """Minutes from the zone's homes to the nearest target of each set (median, p90, share within 5 / 10 min)."""
    h = _api().get(f"/api/zone/{zone_id}/heatmap?sets={sets}&mode={mode}&neighbours={str(neighbours).lower()}")
    lines = [f"{zone_id} · {mode} · {len(h['segments']['features'])} segments · {h['homes']} homes ({h['homes_source']})"
             + (" · cached" if h.get("cached") else "")]
    for s, v in h["summary"].items():
        med = "–" if v["median_s"] is None else f"{v['median_s'] / 60:.1f} min"
        p90 = "–" if v["p90_s"] is None else f"{v['p90_s'] / 60:.1f} min"
        lines.append(f"  {s:10} median {med:9} p90 {p90:9} ≤5 min {v['share_le_5min']:.0%} · ≤10 min "
                     f"{v['share_le_10min']:.0%} · {v['targets']} targets")
    _out({k: v for k, v in h.items() if k != "segments"}, "\n".join(lines))


@zone_app.command("indices")
def zone_indices_cmd(zone_id: Optional[str] = typer.Argument(None, help="one zone; omit with --all"),
                     all_zones: bool = typer.Option(False, "--all", help="compute every zone (a few seconds each)")):
    """Mobility indices (transport, transport + services): one zone, or fill the cache for every zone."""
    api = _api()
    if not all_zones:
        if not zone_id:
            typer.secho("give a zone id or --all", fg="red", err=True)
            raise typer.Exit(2)
        r = api.get(f"/api/zone/{zone_id}/indices")
        m = r["measured"]
        lines = [f"{zone_id}: transport {r['transport']} · transport + services {r['transport_services']} · services {r['services']}"]
        lines += [f"  {w:10} transport {v['transport']} · lines {m['lines'].get(w)} · {m['frequency'].get(w)}/h"
                  for w, v in r["windows"].items()]
        lines.append(f"  walk: rail {m['rail_access_min']} min · bus {m['bus_access_min']} min · coverage {m['coverage']}"
                     f" · {m['reachable_stops']} stops within reach")
        _out(r, "\n".join(lines))
        return
    zones = api.get("/api/geo/zones")                  # served as application/geo+json: the client returns text
    ids = [f["properties"]["zone_id"] for f in (json.loads(zones) if isinstance(zones, str) else zones)["features"]]
    for done, zid in enumerate(ids, 1):
        r = api.get(f"/api/zone/{zid}/indices")
        if not r.get("cached"):
            typer.echo(f"{done}/{len(ids)} {zid}: transport {r['transport']} · + services {r['transport_services']}")
    _out({"zones": len(ids)}, f"indices ready for {len(ids)} zones")


@zone_app.command("centroids")
def zone_centroids_cmd():
    """Build every zone's connectivity centroids (stations within a short walk of its homes; runs locally)."""
    from findhome.config.loader import load_all
    from findhome.geo.store import load_zones
    from findhome.zone.centroid_build import build_centroids

    zones = load_zones()
    if zones is None:
        typer.secho("zones not built yet: findhome geo fetch zones", fg="red", err=True)
        raise typer.Exit(2)
    meta = build_centroids(load_all(), zones, progress=lambda n, t, z: typer.echo(f"{n}/{t} {z}", err=True) if n % 25 == 0 else None)
    _out(meta, f"centroids: {meta['centroids']} in {meta['zones']} zones ({meta['groups']}), {meta['stations']} unique stations,"
               f" max {meta['max_per_zone']} per zone")


