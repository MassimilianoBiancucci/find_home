@config_app.command("schema")
def config_schema(which: str = typer.Argument("ingest", help="ingest"),
                  markdown: bool = typer.Option(False, "--markdown")):
    """Print the agent → app contract (ListingIn, EvaluationIn) as JSON Schema or Markdown."""
    from findhome.domain.models import EvaluationIn, ListingIn, SourceIn

    models = {"ListingIn": ListingIn, "SourceIn": SourceIn, "EvaluationIn": EvaluationIn}
    if not markdown:
        _out({k: m.model_json_schema() for k, m in models.items()})
        return
    lines = ["<!-- generated by `findhome config schema ingest --markdown`; do not edit -->"]
    for name, model in models.items():
        lines += [f"\n### {name}\n", "| Field | Type | Required | Description |", "|---|---|---|---|"]
        for fname, f in model.model_fields.items():
            ann = str(f.annotation).replace("typing.", "").replace("<class '", "").replace("'>", "")
            ann = ann.replace("findhome.domain.models.", "").replace("|", "\\|")
            lines.append(f"| `{fname}` | {ann} | {'yes' if f.is_required() else ''} | {f.description or ''} |")
    typer.echo("\n".join(lines))


